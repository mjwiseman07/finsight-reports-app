#!/usr/bin/env node
/**
 * Read-only generator: consolidates pre-phase1 local migrations into a single
 * draft baseline migration for review. Does NOT touch production or branches.
 *
 * Uses explicit dependency manifest + fail-closed replay validation.
 * Excludes production backfills and operational DML. Preserves allowlisted
 * reference data only. Flattens nested transactions from source files.
 */
const fs = require("fs");
const path = require("path");
const {
  loadManifest,
  orderedFilesFromPhases,
  validateManifestGraph,
  validateFileOrder,
  validateBaselineSql,
  lexicographicSourceOrder,
} = require("./baseline-sql-analyzer");

const ROOT = path.join(__dirname, "..", "..");
const SRC_DIR = path.join(ROOT, "supabase", "migrations");
const OUT_FILE = path.join(ROOT, "supabase", "migrations-draft", "20260701043599_foundations_baseline.sql");

/** Reference-data INSERT targets permitted in baseline. */
const REFERENCE_INSERT_ALLOWLIST = new Set(["company_roles"]);

function stripOperationalDml(sql, filename) {
  let out = sql;
  out = out.replace(
    /^update\s+public\.\w+[\s\S]*?;\s*$/gim,
    "-- [BASELINE_OMIT operational UPDATE removed from " + filename + "]\n",
  );
  out = out.replace(/insert\s+into\s+public\.(\w+)[\s\S]*?;\s*(?=\n|$)/gim, (match, table) => {
    if (REFERENCE_INSERT_ALLOWLIST.has(table.toLowerCase())) return match;
    if (/select\s+[\s\S]*?\bfrom\b/i.test(match)) {
      return `-- [BASELINE_OMIT production backfill INSERT removed from ${filename}]\n`;
    }
    return match;
  });
  return out;
}

function stripCompatibilityLift(sql) {
  return sql.replace(
    /-- Compatibility lift[\s\S]*?end \$\$;\s*/gi,
    "-- [BASELINE_OMIT compatibility lift backfill block removed]\n",
  );
}

function flattenTransactions(sql) {
  return sql
    .replace(/^\s*begin\s*;\s*$/gim, "-- [BASELINE_FLATTEN nested BEGIN removed]")
    .replace(/^\s*commit\s*;\s*$/gim, "-- [BASELINE_FLATTEN nested COMMIT removed]");
}

function buildHeader(files, manifest) {
  return `-- ============================================================================
-- DRAFT: foundations baseline for Supabase preview-branch replay remediation
-- Version: 20260701043599 (intentionally before phase1_subscriptions_core)
--
-- STATUS: DRAFT — NOT APPROVED. Do not place in supabase/migrations/ without sign-off.
-- Generated by: scripts/migration-remediation/generate-foundations-baseline.js
-- Ordering: explicit dependency manifest (NOT lexicographic filename sort)
-- Manifest: docs/migration-remediation/baseline-source-dependency-manifest.json
--
-- Composition:
--   - foundation schema DDL from ${files.length} pre-phase1 local migrations
--   - allowlisted reference data: company_roles seed only
--   - EXCLUDED: production backfills, operational UPDATE/INSERT...SELECT
--
-- Source files (dependency order):
${files.map((f) => `--   - ${f}`).join("\n")}
--
-- Excluded files:
${manifest.excludeFiles.map((f) => `--   - ${f}`).join("\n")}
-- ============================================================================

BEGIN;
`;
}

function buildFooter() {
  return `
COMMIT;
`;
}

function main() {
  const manifest = loadManifest();
  const graph = validateManifestGraph(manifest);
  if (!graph.ok) {
    console.error("Manifest dependency graph invalid:", graph.errors);
    process.exit(1);
  }

  const files = orderedFilesFromPhases(manifest);
  const lex = lexicographicSourceOrder(manifest, SRC_DIR);
  if (lex.join("|") === files.join("|")) {
    console.error("FAIL CLOSED: dependency order equals lexicographic sort — unsafe");
    process.exit(1);
  }

  const preValidation = validateFileOrder(files, manifest, SRC_DIR);
  if (!preValidation.ok) {
    console.error("FAIL CLOSED: source order fails replay simulation");
    console.error(JSON.stringify(preValidation.violations.slice(0, 5), null, 2));
    process.exit(1);
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

  const parts = [buildHeader(files, manifest)];
  for (const file of files) {
    let sql = fs.readFileSync(path.join(SRC_DIR, file), "utf8").trim();
    sql = stripCompatibilityLift(sql);
    sql = stripOperationalDml(sql, file);
    sql = flattenTransactions(sql);
    parts.push(`\n-- >>> SOURCE: ${file}\n`);
    parts.push(sql);
    parts.push("\n");
  }
  parts.push(buildFooter());

  const outSql = parts.join("\n");
  fs.writeFileSync(OUT_FILE, outSql, "utf8");

  const postValidation = validateBaselineSql(outSql, manifest);
  if (!postValidation.ok) {
    console.error("FAIL CLOSED: generated baseline fails replay simulation");
    console.error(JSON.stringify(postValidation.violations.slice(0, 5), null, 2));
    process.exit(1);
  }

  const bytes = fs.statSync(OUT_FILE).size;
  console.log(
    JSON.stringify(
      {
        outFile: OUT_FILE,
        sourceFiles: files.length,
        excluded: manifest.excludeFiles,
        ordering: "dependency_manifest",
        bytes,
        replayValidation: "pass",
      },
      null,
      2,
    ),
  );
}

main();
