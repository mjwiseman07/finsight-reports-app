#!/usr/bin/env node
/**
 * Read-only generator: consolidates pre-phase1 local migrations into a single
 * draft baseline migration for review. Does NOT touch production or branches.
 *
 * Usage:
 *   node scripts/migration-remediation/generate-foundations-baseline.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC_DIR = path.join(ROOT, 'supabase', 'migrations');
const OUT_DIR = path.join(ROOT, 'supabase', 'migrations-draft');
const OUT_FILE = path.join(OUT_DIR, '20260701043599_foundations_baseline.sql');
const PHASE1_CUTOFF = '20260701043602';

// refund_requests is post-phase1 in production history; keep it out of baseline.
const EXCLUDE = new Set(['20260701_refund_requests.sql']);

function listSourceFiles() {
  return fs
    .readdirSync(SRC_DIR)
    .filter((f) => f.endsWith('.sql') && f < `${PHASE1_CUTOFF}_` && !EXCLUDE.has(f))
    .sort();
}

function buildHeader(files) {
  return `-- ============================================================================
-- DRAFT: foundations baseline for Supabase preview-branch replay remediation
-- Version: 20260701043599 (intentionally before phase1_subscriptions_core)
--
-- STATUS: DRAFT — do not apply to production without migration repair workflow.
-- Generated by: scripts/migration-remediation/generate-foundations-baseline.js
-- Source files (${files.length}):
${files.map((f) => `--   - ${f}`).join('\n')}
--
-- Production: mark applied via \`supabase migration repair --status applied\`
-- Preview (empty DB): executes before phase1 spine to create firms/companies/etc.
-- ============================================================================

BEGIN;
`;
}

function buildFooter() {
  return `
COMMIT;
`;
}

function main() {
  const files = listSourceFiles();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const parts = [buildHeader(files)];
  for (const file of files) {
    const sql = fs.readFileSync(path.join(SRC_DIR, file), 'utf8').trim();
    parts.push(`\n-- >>> SOURCE: ${file}\n`);
    parts.push(sql);
    parts.push('\n');
  }
  parts.push(buildFooter());

  fs.writeFileSync(OUT_FILE, parts.join('\n'), 'utf8');

  const bytes = fs.statSync(OUT_FILE).size;
  console.log(JSON.stringify({ outFile: OUT_FILE, sourceFiles: files.length, bytes }, null, 2));
}

main();
